package com.huanhren.deltaharmonica.input

import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runInterruptible
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import java.io.IOException
import java.util.concurrent.TimeUnit

sealed interface RootCommandResult {
    data class Success(val output: String) : RootCommandResult
    data class Failure(val reason: String, val kind: RootCommandFailureKind = RootCommandFailureKind.COMMAND) : RootCommandResult
    data object TimedOut : RootCommandResult
}

enum class RootCommandFailureKind { LAUNCH, COMMAND }

private val rootDenialMessages = listOf("denied", "not allowed", "not permitted", "unauthorized", "拒绝", "未授权")

internal val RootCommandResult.Failure.authorizationDenied: Boolean
    get() = rootDenialMessages.any { reason.contains(it, ignoreCase = true) }

fun interface RootCommandRunner {
    suspend fun run(command: String, timeoutMs: Long): RootCommandResult
}

/** Only invoked with constant commands generated by RootBackend; no arbitrary user shell input. */
class SuCommandRunner(
    private val launch: (String) -> Process = { ProcessBuilder("su", "-c", it).redirectErrorStream(true).start() },
) : RootCommandRunner {
    override suspend fun run(command: String, timeoutMs: Long): RootCommandResult = withContext(Dispatchers.IO) {
        val started = System.nanoTime()
        fun remaining() = timeoutMs - TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - started)
        val process = try {
            launch(command)
        } catch (e: IOException) {
            return@withContext RootCommandResult.Failure("未找到 su 或无法启动：${e.localizedMessage}", RootCommandFailureKind.LAUNCH)
        } catch (e: SecurityException) {
            return@withContext RootCommandResult.Failure("系统拒绝启动 su", RootCommandFailureKind.LAUNCH)
        }
        // The pipe can outlive su if one of its descendants inherits stdout.
        val output = CompletableDeferred<Result<String>>()
        Thread {
            output.complete(runCatching {
                process.inputStream.bufferedReader().use { reader ->
                    val buffer = CharArray(1024)
                    val result = StringBuilder()
                    while (true) {
                        val count = reader.read(buffer)
                        if (count < 0) break
                        if (result.length < 8192) result.append(buffer, 0, minOf(count, 8192 - result.length))
                    }
                    result.toString().trim()
                }
            })
        }.apply { isDaemon = true; start() }
        try {
            val finished = runInterruptible { process.waitFor(remaining().coerceAtLeast(0), TimeUnit.MILLISECONDS) }
            if (!finished) return@withContext RootCommandResult.TimedOut
            val text = withTimeoutOrNull(remaining()) { output.await().getOrThrow() }
                ?: return@withContext RootCommandResult.TimedOut
            val exitCode = process.exitValue()
            if (exitCode == 0) RootCommandResult.Success(text)
            else RootCommandResult.Failure("su/input 执行失败（退出码 $exitCode）${if (text.isBlank()) "" else "：${text.take(200)}"}")
        } catch (e: IOException) {
            RootCommandResult.Failure("读取 su 结果失败：${e.localizedMessage}")
        } finally {
            if (!output.isCompleted || process.isAlive) {
                runCatching { process.destroyForcibly() }
            }
        }
    }
}
